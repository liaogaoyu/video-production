function buildAssetImagePrompt(prompt, type) {
  const views = type === '角色' || type === 'character'
    ? '左上正面、右上背面、左下左侧面、右下右侧面。单人角色每格均为同一人物的完整全身，面部与头脚不裁切；群体资产每格为同一组人物，人数、身份与站位关系一致。'
    : type === '场景' || type === 'scene'
      ? '左上正向全景、右上反向全景、左下左侧视角、右下右侧视角。四格属于同一空间，建筑、出入口、陈设位置和尺寸互相对应，保持同一剧情时段、天气与光源逻辑，不添加人物。'
      : '左上正面、右上背面、左下左侧面、右下右侧面。四格展示同一件道具的完整外形，结构、比例、材质和磨损一致，不额外加入手持人物。';
  return `${String(prompt || '').trim()}\n\n【默认资产四视图版式】\n只生成一张包含四视图的资产设定图，采用2×2等大四宫格，四格边界清楚。${views}四格使用同一美术风格、色彩与材质基准，主体不变形、不换装、不换款，不做剧情连续动作或不同状态对比。此版式优先于前文的单视角、多动作、局部细节拼图要求；保留原文明确的年代、外观与必要道具文字。不添加视图标题、角标、字幕或水印；整张图片沿用本次请求画幅。`;
}

module.exports = { buildAssetImagePrompt };
