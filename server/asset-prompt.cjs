function buildAssetImagePrompt(prompt, type) {
  const source = String(prompt || '').trim();
  const heading = '【资产最终展示版式】';
  const layout = type === '角色' || type === 'character'
    ? '生成一张人物多视角设定板，左侧占整图宽度约65%、右侧约35%。左侧三列等宽，从左到右依次为正面全身、侧面全身、背面全身，人物站立，三列头顶与脚底对齐、身高比例一致、完整全身不裁切。右侧上下两格：上格为清晰的正面面部及肩部特写，下格为摄像机从头顶向下拍摄的俯视图，人物仍自然直立，不用低头鞠躬替代俯视机位。共五个展示区域，左侧三列不切成上下两排；浅灰或中性背景、统一柔光，所有区域保持同一人物的脸、发型、服装与配饰；群体资产各区域沿用同一群体。版式只规定展示方式，人物外观与画风按正文设计。'
    : type === '场景' || type === 'scene'
      ? '生成一张2×2等大四宫格场景设定图：左上正面视角、右上侧面视角、左下背面视角、右下高位俯拍全景。俯拍格从上方清楚交代建筑、道路、院落或室内空间的整体布局。四格属于同一空间，建筑、出入口、陈设位置和尺寸互相对应，保持同一剧情时段、天气与光源逻辑，不添加人物。格间用细浅色分隔线；可仅在各格左上角分别标注“正面视角图”“侧面视角图”“背面视角图”“俯拍图”，不添加其他说明。版式只规定排版和机位，场景内容与画风按正文设计。'
      : '生成一张单幅道具主体展示图，单一主体或原文指定的道具组合，采用最能看清外形与结构的自然三分之四角度，完整展示主体，背景简洁、材质清楚、保留合理接触阴影。不做四视图、不做四宫格、不拼接正背侧面，不额外加入手持人物。纸张、照片等平面道具以可辨识的正面内容为主，必要的正反面或不同状态应分别生成独立图片，不在同一图中拼版。';
  const scope = type === '场景' || type === 'scene'
    ? '【场景资产范围】本次生成无人环境底板，座椅空置、通道空置，保留建筑、家具、设备和陈设。即使正文提及场景使用者或剧情人物，也只理解为空间用途，不绘制这些人物；前景、背景、远处、倒影及屏幕中均不新增人物或人群。本范围要求优先于正文中的人物出镜描述。\n\n'
    : '';
  return `${scope}${source}\n\n${heading}\n${layout}\n以上为最终展示版式，替代正文中旧的2×2人物四视图或道具四视图要求；主体设计、年代、材质、服装与项目美术风格仍以正文为准。不要生成水印；人物和道具不加视图标题。整张图片沿用本次请求画幅，在该画幅内保持所述区域关系。`;
}

module.exports = { buildAssetImagePrompt };
